// Writes yomitan-parser/data/hanja_eum.txt: the Hangul readings (eum) of each Hanja that
// has more than one, from libhangul's hanja.txt (BSD-3-Clause), for the Characters view.
//
//   node scripts/hanja-eum.mjs [path/to/hanja.txt]
//
// Without a path, it downloads hanja.txt from libhangul's repository.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const URL_ =
  "https://raw.githubusercontent.com/libhangul/libhangul/main/data/hanja/hanja.txt";
const OUT = fileURLToPath(
  new URL("../yomitan-parser/data/hanja_eum.txt", import.meta.url),
);

const src = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch(URL_)).text();

const lines = src.split("\n");
// libhangul's copyright and license, which the BSD license says to keep
const notice = [];
for (const l of lines) {
  if (!l.startsWith("#")) break;
  notice.push(l);
}

/** @type {Map<string, string[]>} Hanja -> readings, in hanja.txt's order */
const eum = new Map();
for (const l of lines) {
  if (l.startsWith("#")) continue;
  const [hangul, hanja] = l.split(":");
  if (!hangul || !hanja || [...hanja].length !== 1) continue;
  const rs = eum.get(hanja) ?? [];
  if (!rs.includes(hangul)) rs.push(hangul);
  eum.set(hanja, rs);
}

const rows = [...eum].filter(([, rs]) => rs.length > 1);
const out = [
  "# Hangul readings (eum) of each Hanja with more than one, tab-separated:",
  "# Hanja, then its readings, space-separated. Generated by scripts/hanja-eum.mjs from",
  `# ${URL_}`,
  "#",
  ...notice,
  ...rows.map(([h, rs]) => `${h}\t${rs.join(" ")}`),
  "",
].join("\n");
await writeFile(OUT, out);
console.log(`${rows.length} Hanja with several readings -> ${OUT}`);
